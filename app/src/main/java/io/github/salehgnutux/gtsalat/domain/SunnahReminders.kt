package io.github.salehgnutux.gtsalat.domain

import java.time.DayOfWeek

/**
 * تذكيراتُ السُّنن الموسميّة حسب التاريخ الهجريّ ويوم الأسبوع (على غرار الأيّام البيض):
 * صيام الاثنين والخميس، سنن الجمعة، عاشوراء، عرفة، عشر ذي الحجّة، ستّ من شوّال… إلخ.
 * تُعيد رسالةً واحدةً مناسبةً لليوم (بأولويّة المناسبة الهجريّة الخاصّة على السُّنّة الأسبوعيّة)
 * فلا يزدحم المستخدم بأكثرَ من تذكيرٍ في اليوم. النصوص من سننٍ ثابتةٍ صحيحة.
 *
 * @param hMonth الشهر الهجريّ 1..12 (1=محرّم). @param hDay يوم الشهر الهجريّ 1..30.
 */
object SunnahReminders {

    /** (عنوانٌ مختصر، نصّ) لتذكير اليوم، أو null إن لم يكن ثمّة سنّةٌ موسميّة اليوم. */
    fun messageFor(hMonth: Int, hDay: Int, weekday: DayOfWeek): Pair<String, String>? {
        // ① مناسباتٌ هجريّةٌ خاصّة (أولويّة عليا)
        when (hMonth) {
            1 -> when (hDay) { // محرّم
                9 -> return "عاشوراء" to "غداً عاشوراء (10 محرّم): صيامه يكفّر السنةَ الماضية. ويُستحبّ صيام التاسوعاء معه — فصُم اليوم (9 محرّم)."
                10 -> return "عاشوراء" to "اليومَ عاشوراء (10 محرّم): صيامه يكفّر السنةَ الماضية، صيامٌ مستحبّ."
                1 -> return "المحرّم" to "شهرُ الله المحرّم: «أفضلُ الصيام بعد رمضان صيامُ شهر الله المحرّم». فأكثِر فيه من الصيام."
            }
            8 -> if (hDay == 1) return "شعبان" to "دخل شعبان: كان النبيُّ ﷺ يُكثر الصيام فيه حتى يكاد يصومه كلَّه. فأكثِر من الصيام."
            10 -> if (hDay == 2) return "ستٌّ من شوّال" to "ستٌّ من شوّال: «مَن صام رمضان ثمّ أتبعه ستّاً من شوّال فكأنّما صام الدهر». فبادِر بها هذا الشهر."
            12 -> when (hDay) { // ذو الحجّة
                9 -> return "يوم عرفة" to "اليومَ يومُ عرفة (9 ذي الحجّة): صيامه لغير الحاجّ يكفّر سنتين — الماضية والباقية."
                8 -> return "يوم عرفة" to "غداً يومُ عرفة (9 ذي الحجّة): صيامه لغير الحاجّ يكفّر سنتين. فاستعدَّ له."
                in 1..7 -> return "عشر ذي الحجّة" to "من عشرِ ذي الحجّة: «ما من أيّامٍ العملُ الصالحُ فيهنّ أحبُّ إلى الله من هذه». أكثِر من الذكر والتكبير والصيام."
            }
        }
        // ② سننٌ أسبوعيّة
        return when (weekday) {
            DayOfWeek.MONDAY, DayOfWeek.THURSDAY ->
                "صيام الاثنين والخميس" to "اليومَ يُستحبّ صيامه: «تُعرَض الأعمالُ يومَ الاثنين والخميس، فأُحبُّ أن يُعرَض عملي وأنا صائم»."
            DayOfWeek.FRIDAY ->
                "سنن الجمعة" to "اليومَ الجمعة: اقرأ سورة الكهف، وأكثِر الصلاة على النبيّ ﷺ، وبكّر إلى الجُمعة، واغتنِم ساعةَ الإجابة."
            else -> null
        }
    }
}
