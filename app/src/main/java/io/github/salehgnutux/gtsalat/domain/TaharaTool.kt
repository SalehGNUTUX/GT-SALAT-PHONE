package io.github.salehgnutux.gtsalat.domain

/**
 * أداةُ «طهرت الآن، ماذا أصلّي؟» — **النسخة الإرشاديّة (ب)**: تعليميّةٌ لا تُصدر حكمًا قاطعًا مُلزِمًا،
 * بل تعرض القاعدة المالكيّة العامّة وتُحيل المسائل الخاصّة لأهل العلم (كما تنصّ الخطّة §27.8).
 * تُستبدل/تُجمَع لاحقًا بالنسخة الخوارزميّة (أ) بعد تثبيت جداول الأوقات فقهيًّا.
 */
object TaharaTool {

    /** جواب سؤال تحقّق الطهر. */
    enum class Purity { CONFIRMED, NOT_YET, UNSURE }

    /** إرشادٌ نصّيٌّ (الحقول الفارغة لا تُعرَض). */
    data class Guidance(
        val title: String,
        val ghusl: String = "",
        val currentPrayer: String = "",
        val previousPrayer: String = "",
        val missed: String = "",
        val reason: String = "",
        val source: String = "الرسالة لابن أبي زيد، ومختصر خليل — باب الحيض",
        val consult: String = "لضبط أوقات الاختيار والضرورة وحالتكِ الخاصّة، راجِعي أهل العلم.",
    )

    fun guide(purity: Purity): Guidance = when (purity) {
        Purity.CONFIRMED -> Guidance(
            title = "تحقّق الطهر — هذا الإرشاد العامّ",
            ghusl = "يجب الغسل (غسل الحيض/النفاس) فورًا، ثمّ تُصلّين.",
            currentPrayer = "تلزمكِ الصلاة الحاضرة إن أدركتِ من وقتها قدرَ ركعةٍ فأكثر قبل خروجه.",
            previousPrayer = "وقد تلزم الصلاة التي قبلها إن كانت تُجمع مع الحاضرة (الظهر مع العصر، والمغرب مع العشاء) في أوقات الضرورة، على تفصيلٍ في المذهب المالكيّ.",
            missed = "لا تُقضى الصلوات التي مرّت أثناء الحيض (بخلاف صيام رمضان فيُقضى).",
            reason = "لأنّ الطهر يرفع مانع الحيض، فتلزم الصلاة بإدراك وقتها.",
        )
        Purity.NOT_YET -> Guidance(
            title = "لم يتحقّق الطهر بعد",
            ghusl = "لا تغتسلي للحيض ولا تصلّي حتى تتيقّني الطهر بعلامته.",
            missed = "الحائض لا تصلّي، ولا تقضي صلاة أيّام الحيض.",
            reason = "لأنّ علامة الطهر (القصّة البيضاء أو الجفوف) لم تظهر بعد.",
        )
        Purity.UNSURE -> Guidance(
            title = "عند الشكّ: الأصل بقاء الحيض",
            ghusl = "لا تعجَلي؛ الأصل بقاء الحيض حتى يتيقّن الطهر بعلامته.",
            reason = "لأنّ اليقين لا يزول بالشكّ.",
        )
    }
}
